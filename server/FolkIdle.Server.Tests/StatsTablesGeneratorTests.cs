using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using FolkIdle.Server.Domain.Progression;
using FolkIdle.Server.Domain.Shared;
using FolkIdle.Server.Engine;
using Xunit;

namespace FolkIdle.Server.Tests
{
    /// <summary>
    /// Writes docs/architecture/STATS_TABLES.md from the server's own
    /// registries, and fails when the committed file no longer matches them.
    /// </summary>
    /// <remarks>
    /// Modul: A STATS DOCUMENT THAT CANNOT DRIFT (2026-11-20). STATS_REFERENCE.md
    /// was written by hand on 2026-10-29 and within three weeks described a
    /// 20-node skill tree the game had replaced with 63 nodes and keystones,
    /// and knew nothing of Nav, the Chronicle or the rare pets. Prose explains;
    /// numbers belong in a file the code writes. This is the same contract as
    /// generate-protocol.mjs --check: a change to a registry that does not
    /// regenerate the tables fails CI, so the tables are always the game.
    ///
    /// Regenerate: set FOLKIDLE_UPDATE_STATS_TABLES=1 and run this test
    /// (dotnet test --filter StatsTablesGeneratorTests).
    /// </remarks>
    public class StatsTablesGeneratorTests
    {
        private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        [Fact]
        public void TheCommittedStatsTablesMatchTheRegistries()
        {
            ContentRegistry.Initialize();
            string generated = Generate();
            string path = Path.Combine(RepoRoot(), "docs", "architecture", "STATS_TABLES.md");

            if (Environment.GetEnvironmentVariable("FOLKIDLE_UPDATE_STATS_TABLES") == "1")
            {
                File.WriteAllText(path, generated, new UTF8Encoding(false));
                return;
            }

            Assert.True(File.Exists(path), "docs/architecture/STATS_TABLES.md is missing - run with FOLKIDLE_UPDATE_STATS_TABLES=1");
            string committed = File.ReadAllText(path).Replace("\r\n", "\n");
            Assert.True(committed == generated,
                "docs/architecture/STATS_TABLES.md is stale: a registry changed. Regenerate with FOLKIDLE_UPDATE_STATS_TABLES=1 " +
                "(dotnet test --filter StatsTablesGeneratorTests) and commit the file.");
        }

        private static string RepoRoot()
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null && !Directory.Exists(Path.Combine(dir.FullName, "docs", "architecture"))) dir = dir.Parent;
            return dir?.FullName ?? throw new InvalidOperationException("repository root not found");
        }

        private static string N(long v) => v.ToString("N0", Inv);
        private static string P(double v) => v.ToString("0.##", Inv);

        internal static string Generate()
        {
            var sb = new StringBuilder();
            void L(string line = "") => sb.Append(line).Append('\n');

            L("# FolkIdle stats tables (generated)");
            L();
            L("GENERATED by `server/FolkIdle.Server.Tests/StatsTablesGeneratorTests.cs` from the");
            L("server's registries. Do not edit by hand: CI fails when this file and the code");
            L("disagree. Regenerate with `FOLKIDLE_UPDATE_STATS_TABLES=1` and");
            L("`dotnet test --filter StatsTablesGeneratorTests`. The formulas and the reasons");
            L("behind them are in `STATS_REFERENCE.md`; the best order to play is in");
            L("`docs/design/PLAYER_PATH.md`.");
            L();

            // ---- levels ----
            L("## 1. Levels");
            L();
            L("XP to the next level (`ProgressionEngine.GetRequiredXpForLevel`) and base health");
            L("(`BaseMilliHpForLevel`, whole HP).");
            L();
            L("| Level | XP to next | Cumulative XP | Base HP |");
            L("|---:|---:|---:|---:|");
            foreach (int level in new[] { 1, 5, 10, 15, 20, 25, 30, 40, 50, 60, 70, 80, 90, 100, 120, 150 })
            {
                L($"| {level} | {N(ProgressionEngine.GetRequiredXpForLevel(level))} | {N(ProgressionEngine.CumulativeXp(level, 0))} | {N(ProgressionEngine.BaseMilliHpForLevel(level) / 1000)} |");
            }
            L();

            // ---- monsters ----
            L("## 2. Region monsters");
            L();
            L("Ids 91-115, five per region, the fifth is the region boss. Health and attack are");
            L("the scaled values the fight uses (`GetScaledMonsterMaxHp`, `GetScaledMonsterAttackPower`).");
            L();
            L("| Id | Monster | Region | HP | Attack | Swing (ms) | Armour | Dodge | XP | Gold |");
            L("|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|");
            foreach (var m in ContentRegistry.Monsters.ToArray().Where(m => m.Id >= ContentRegistry.FirstCanonicalMonsterId && m.Id <= ContentRegistry.FirstCanonicalMonsterId + 24).OrderBy(m => m.Id))
            {
                string boss = ContentRegistry.IsRegionalBoss(m.Id) ? " (boss)" : "";
                L($"| {m.Id} | {ContentRegistry.GetMonsterName(m.Id)}{boss} | {ContentRegistry.GetMonsterRegionTier(m.Id)} | {N(ContentRegistry.GetScaledMonsterMaxHp(m.Id))} | {N(ContentRegistry.GetScaledMonsterAttackPower(m.Id))} | {m.AttackIntervalMs} | {N(m.Armor)} | {m.DodgeRating} | {N(m.BaseXpReward)} | {N(m.BaseGoldReward)} |");
            }
            L();

            // ---- skill tree ----
            L("## 3. War skill tree");
            L();
            L($"Columns: {string.Join(", ", WarTreeRegistry.ColumnNames)}. Points needed in the tree to open each row: {string.Join(", ", WarTreeRegistry.RowGates)}.");
            L("Only one keystone can be held. Hidden nodes are built but not offered.");
            L();
            L("| Id | Node | Column | Row | Kind | Max rank | Cost / rank | Effect at max rank | Hidden |");
            L("|---:|---|---|---:|---|---:|---:|---|---|");
            foreach (var n in WarTreeRegistry.All().OrderBy(n => n.Row).ThenBy(n => n.Column).ThenBy(n => n.Id))
            {
                string col = n.Column >= 0 && n.Column < WarTreeRegistry.ColumnNames.Length ? WarTreeRegistry.ColumnNames[n.Column] : n.Column.ToString(Inv);
                // The value at full rank, as the screen prints it.
                string effect = WarTreeRegistry.EffectAt(n.Id, n.MaxLevel).Replace("|", "/").Replace("\n", " ");
                L($"| {n.Id} | {n.Name} | {col} | {n.Row} | {n.Kind} | {n.MaxLevel} | {n.CostPerRank} | {effect} | {(n.Hidden ? "yes" : "")} |");
            }
            L();

            // ---- affixes ----
            L("## 4. Affixes");
            L();
            L("Base value and growth per item tier, in tenths of a percent as stored.");
            L();
            L("| Affix | Law | Base (0.1%) | Growth / tier (0.1%) | Utility | Retired |");
            L("|---|---|---:|---:|---|---|");
            foreach (var a in AffixRegistry.Definitions.ToArray())
            {
                L($"| {a.Id} | {a.Law} | {a.BaseValueTenthsPct} | {a.GrowthTenthsPctPerTier} | {(a.Utility ? "yes" : "")} | {(a.Retired ? "yes" : "")} |");
            }
            L();
            L("| Affix rarity | Multiplier |");
            L("|---|---:|");
            foreach (AffixRarity r in Enum.GetValues(typeof(AffixRarity)))
            {
                L($"| {r} | {P(AffixRegistry.GetAffixRarityMultiplier(r))} |");
            }
            L();

            // ---- pets ----
            L("## 5. Pets");
            L();
            L("| Pet | Source | Bonuses |");
            L("|---|---|---|");
            foreach (var pet in PetRegistry.All.OrderBy(p => p.Source).ThenBy(p => p.Id, StringComparer.Ordinal))
            {
                L($"| {pet.Name} | {pet.Source} | {string.Join(", ", pet.Bonuses.Select(b => $"+{b.Pct}% {b.Stat}"))} |");
            }
            L();

            // ---- potions ----
            L("## 6. Potions");
            L();
            L("| Item id | Kind | Shelf | Strong | Minutes | Magnitude |");
            L("|---:|---|---:|---|---:|---:|");
            foreach (var p in PotionRegistry.All.OrderBy(p => p.ItemId))
            {
                L($"| {p.ItemId} | {p.Kind} | {p.Slot} | {(p.Strong ? "yes" : "")} | {p.DurationMs / 60000} | {p.Magnitude} |");
            }
            L();

            // ---- inheritance ----
            L("## 7. Inheritance (diamonds, survives every rebirth)");
            L();
            L($"Each level adds {InheritanceRegistry.PercentPerLevel}% to its stat, up to level {InheritanceRegistry.MaxLevel}.");
            L();
            L("| Stat | " + string.Join(" | ", Enumerable.Range(0, InheritanceRegistry.MaxLevel).Select(i => $"L{i + 1}")) + " |");
            L("|---|" + string.Concat(Enumerable.Repeat("---:|", InheritanceRegistry.MaxLevel)));
            L("| Cost (diamonds) | " + string.Join(" | ", Enumerable.Range(0, InheritanceRegistry.MaxLevel).Select(i => N(InheritanceRegistry.GetUpgradeCost(i)))) + " |");
            L();
            L("Stats: " + string.Join(", ", Enumerable.Range(0, InheritanceRegistry.StatCount).Select(InheritanceRegistry.GetName)) + ".");
            L();

            // ---- rebirth ----
            L("## 8. Rebirth");
            L();
            L($"- Renown from level {RebirthRules.RenownLevel}; damage bonus capped at {RebirthRules.MaxDamageBonusPct}%.");
            L($"- {RebirthRules.SkillPointsPerRebirth} skill points per rebirth; rewards for the first {RebirthRules.RewardedRebirths}; bloodline counts {RebirthRules.BloodlineRebirths}.");
            L($"- +{RebirthRules.ReLevelXpBonusPct}% XP while below the peak level.");
            L();
            L("| Renowned rebirths | Damage bonus |");
            L("|---:|---:|");
            for (int r = 0; r <= 10; r++) L($"| {r} | {RebirthRules.DamageBonusPct(r)}% |");
            L();

            // ---- Nav ----
            L("## 9. Nav (bonuses count inside Nav only)");
            L();
            L($"Depth-1 guardian: {N((long)NavRules.FirstGuardianHp)} HP, {N((long)NavRules.FirstGuardianAttack)} attack; x{P(NavRules.HpGrowth)} HP and x{P(NavRules.AttackGrowth)} attack per depth; " +
              $"a Circle multiplies both by {P(NavRules.CircleStrength)} and Souls by {P(NavRules.CircleSouls)}; the next Circle opens at depth {NavRules.CircleOpensAt}.");
            L();
            L("| Workshop upgrade | Effect | Per level | Base cost (Souls) | Max |");
            L("|---|---|---:|---:|---:|");
            foreach (var u in NavRules.Workshop) L($"| {u.Name} | {u.Effect} | {P(u.PerLevel)} | {N(u.BaseCost)} | {(u.MaxLevel > 0 ? u.MaxLevel.ToString(Inv) : "-")} |");
            L();
            L("| Research (gold) | Effect | Per level | Opens at Circle |");
            L("|---|---|---:|---:|");
            foreach (var r in NavRules.Research) L($"| {r.Name} | {r.Effect} | {P(r.PerLevel)} | {r.OpensAtCircle} |");
            L();

            return sb.ToString();
        }
    }
}
